private val OPERATOR_UPPERCASE_CHINESE = OPERATOR_CHINESE.mapKeys { it.key.uppercase(java.util.Locale.ROOT) }

/** Exact English key lookup with an English fallback. */
public fun operatorText(english: String): String {
    val language = CopyLanguage.preferred()
    if (language != CopyLanguage.SIMPLIFIED_CHINESE) return english
    return OPERATOR_CHINESE[english] ?: OPERATOR_UPPERCASE_CHINESE[english] ?: CopyCatalog.bundled.text(english, language)
}

/** Values such as camera names remain arguments, never translation keys. */
public fun operatorFormat(english: String, vararg values: Any?): String =
    String.format(java.util.Locale.getDefault(), operatorText(english), *values)
